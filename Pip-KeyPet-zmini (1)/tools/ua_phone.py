def main(path):
    s = open(path, encoding='utf-8').read()
    shutil.copy(path, path + '.bak')
    a = s.index('static const char *const words[]'); b = s.index('};', a)
    head, kw, tail = s[:a], s[a:b], s[b:]
    miss = set(); cnt = 0
    def sub(m):
        nonlocal cnt
        t = m.group(1)
        if not re.search('[А-Яа-яЁёҚқ]', t): return m.group(0)
        if t in T:
            cnt += 1; return '"' + T[t] + '"'
        miss.add(t); return m.group(0)
    rx = r'"((?:[^"\\\n]|\\.)*)"'
    head = re.sub(rx, sub, head); tail = re.sub(rx, sub, tail)
    if LOWER_OLD in head and 'p[1] == 0x84' not in head:
        head = head.replace(LOWER_OLD, LOWER_NEW, 1)
    else: print('УВАГА: lower() не змінено (не знайдено місце або вже змінено)')
    head = head.replace('UTF-8 lower case for Latin and Russian', 'UTF-8 lower case for Latin, Russian and Ukrainian')
    if 'підтвердж' not in kw:
        i = kw.rindex(',') + 1
        kw = kw[:i] + '\n ' + UA_WORDS + kw[i:]
    open(path, 'w', encoding='utf-8').write(head + kw + tail)
    print('замінено рядків:', cnt)
    for t in sorted(miss): print('НЕ ПЕРЕКЛАДЕНО:', t)
    left = [l for l in (head+tail).splitlines() if re.search('[ыэъ]', l)]
    for l in left: print('залишок кирилиці (рос.):', l.strip()[:90])
main(sys.argv[1])
